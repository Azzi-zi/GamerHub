package com.example.gamerhub

// Импортируем аннотацию Database для настройки базы данных Room.
import androidx.room.Database

// Импортируем базовый класс RoomDatabase,
// от которого должна наследоваться наша база данных.
import androidx.room.RoomDatabase

// Аннотация @Database сообщает Room, какие таблицы входят в базу данных.
@Database(

    // Перечисляем сущности (таблицы), которые будут храниться в базе данных.
    entities = [

        // Таблица с информацией об играх.
        Game::class,

        // Таблица с профилями пользователей.
        UserProfile::class
    ],

    // Версия базы данных.
    // При изменении структуры таблиц обычно требуется увеличить это число
    // и добавить соответствующую миграцию.
    version = 6,

    // Отключаем экспорт схемы базы данных в JSON-файлы.
    exportSchema = false
)

// Объявляем абстрактный класс локальной базы данных GamerHub.
// Room автоматически создаёт реализацию этого класса во время сборки проекта.
abstract class GamerHubDatabase : RoomDatabase() {

    // Возвращает объект GameDao.
    // Через него приложение выполняет запросы к таблицам базы данных.
    abstract fun gameDao(): GameDao
}